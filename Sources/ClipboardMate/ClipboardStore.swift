    func startQueue(with queueItems: [ClipItem], order: QueueOrder? = nil) {
        guard !queueItems.isEmpty else { return }
        let effectiveOrder = order ?? queueOrder
        var orderedItems = queueItems
        switch effectiveOrder {
        case .fifo:
            orderedItems.sort { $0.createdAt < $1.createdAt }
        case .lifo:
            orderedItems.sort { $0.createdAt > $1.createdAt }
        case .selection:
            break
        }
        pasteQueue = orderedItems
        poppedHistory.removeAll()

        // 核心机制：启动时立即将首项预载入系统剪贴板，用户按 ⌘V 即可立即原生粘贴
        if let first = pasteQueue.first {
            writeToPasteboard(first)
        }

        onQueueChanged?()
        NSHapticFeedbackManager.defaultPerformer.perform(.alignment, performanceTime: .default)
    }

    /// 推进队列：标记当前项已粘贴，并自动将下一项装填至系统剪贴板
    @discardableResult
    func advanceQueue() -> ClipItem? {
        guard !pasteQueue.isEmpty else { return nil }
        let popped = pasteQueue.removeFirst()
        poppedHistory.append(popped)

        // 若队列中还有后续条目，自动将下一项预载入系统剪贴板
        if let next = pasteQueue.first {
            writeToPasteboard(next)
        }

        NSHapticFeedbackManager.defaultPerformer.perform(.alignment, performanceTime: .default)
        onQueueChanged?()

        if pasteQueue.isEmpty && !isCollectModeActive {
            onQueueFinished?()
        }
        return popped
    }

    @discardableResult
    func undoQueuePop() -> ClipItem? {
        guard let lastPopped = poppedHistory.popLast() else { return nil }
        pasteQueue.insert(lastPopped, at: 0)

        // 重新把回退的项写入系统剪贴板
        writeToPasteboard(lastPopped)

        onQueueChanged?()
        NSHapticFeedbackManager.defaultPerformer.perform(.alignment, performanceTime: .default)
        return lastPopped
    }

    @discardableResult
    func popNextQueueItem() -> ClipItem? {
        guard !pasteQueue.isEmpty else { return nil }
        let current = pasteQueue[0]
        writeToPasteboard(current)

        if autoPasteEnabled {
            PasteSimulator.paste()
        }

        return advanceQueue()
    }

    func clearQueue() {
        pasteQueue.removeAll()
        poppedHistory.removeAll()
        isCollectModeActive = false
        queuePasteBusy = false
        onQueueChanged?()
    }

