    func startMonitoring(interval: TimeInterval = 0.15) {
        lastSeenChangeCount = NSPasteboard.general.changeCount
        let pollTimer = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            self?.poll()
        }
        RunLoop.main.add(pollTimer, forMode: .common)
        timer = pollTimer
    }

    private let appIconCache = NSCache<NSString, NSImage>()

    func appIcon(for bundleId: String?) -> NSImage? {
        guard let bundleId = bundleId, !bundleId.isEmpty else { return nil }
        if let cached = appIconCache.object(forKey: bundleId as NSString) {
            return cached
        }
        if let appURL = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleId) {
            let icon = NSWorkspace.shared.icon(forFile: appURL.path)
            icon.size = NSSize(width: 16, height: 16)
            appIconCache.setObject(icon, forKey: bundleId as NSString)
            return icon
        }
        return nil
    }

    // MARK: - 采集

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastSeenChangeCount else { return }
        lastSeenChangeCount = pb.changeCount

        let source = resolveSourceApp()

        if ignoreSensitiveData {
            if let types = pb.types, types.contains(where: { sensitiveTypes.contains($0) }) {
                return
            }
            if let bundleId = source.bundleId, Self.passwordManagerBundleIds.contains(bundleId) {
                return
            }
        }

        if isBlacklisted(bundleId: source.bundleId) {
            return
        }

        // 1. 优先捕获访达复制的文件/文件夹
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty,
           (pb.types?.contains(NSPasteboard.PasteboardType("NSFilenamesPboardType")) == true ||
            pb.types?.contains(.fileURL) == true) {
            let paths = urls.map { $0.standardizedFileURL.path }
            if paths.contains(where: { FileManager.default.fileExists(atPath: $0) }) {
                addFiles(paths, appName: source.name, bundleId: source.bundleId)
                return
            }
        }

        let pngData = imagePNGData(from: pb)
        let html = cappedRichText(pb.string(forType: .html))
        let rtf = cappedRichData(pb.data(forType: .rtf))
        let plain = extractPlainText(from: pb, html: html, rtf: rtf)

        // 2. 网页复制图片时剪贴板常同时带 URL/替代文本；此时优先收图。
        if let pngData, shouldPreferImage(overText: plain, html: html) {
            addImage(pngData, appName: source.name, bundleId: source.bundleId)
            return
        }

        // 3. 文本（保留 HTML/RTF，供 ⌥Enter 去格式）
        if let plain, !plain.isEmpty {
            addText(plain, html: html, rtf: rtf, appName: source.name, bundleId: source.bundleId)
            return
        }

        // 4. 纯图片
        if let pngData {
            addImage(pngData, appName: source.name, bundleId: source.bundleId)
        }
    }

    private func resolveSourceApp() -> (name: String?, bundleId: String?) {
        let ownID = Bundle.main.bundleIdentifier
        if let bundleId = NSPasteboard.general.string(forType: Self.nspasteboardSourceType),
           !bundleId.isEmpty,
           bundleId != ownID {
            let running = NSWorkspace.shared.runningApplications.first { $0.bundleIdentifier == bundleId }
            let name = running?.localizedName
                ?? NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleId).flatMap { Bundle(url: $0)?.infoDictionary?["CFBundleName"] as? String }
            return (name, bundleId)
        }
        if let front = NSWorkspace.shared.frontmostApplication, front.bundleIdentifier != ownID {
            return (front.localizedName, front.bundleIdentifier)
        }
        return (nil, nil)
    }

    private func extractPlainText(from pb: NSPasteboard, html: String?, rtf: Data?) -> String? {
        if let text = pb.string(forType: .string), !text.isEmpty {
            return text
        }
        if let rtf,
           let attr = NSAttributedString(rtf: rtf, documentAttributes: nil) {
            let value = attr.string.trimmingCharacters(in: .whitespacesAndNewlines)
            if !value.isEmpty { return attr.string }
        }
        if let html, let data = html.data(using: .utf8) {
            let options: [NSAttributedString.DocumentReadingOptionKey: Any] = [
                .documentType: NSAttributedString.DocumentType.html,
                .characterEncoding: String.Encoding.utf8.rawValue
            ]
            if let attr = NSAttributedString(html: data, options: options, documentAttributes: nil) {
                let value = attr.string.trimmingCharacters(in: .whitespacesAndNewlines)
                if !value.isEmpty { return attr.string }
            }
        }
        return nil
    }

    private func shouldPreferImage(overText text: String?, html: String?) -> Bool {
        let trimmed = text?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        if trimmed.isEmpty { return true }
        if looksLikeStandaloneURL(trimmed) { return true }
        guard !trimmed.contains(where: { $0.isNewline }), trimmed.count <= 200 else { return false }
        let lower = trimmed.lowercased()
        let imageExts = [".png", ".jpg", ".jpeg", ".gif", ".webp", ".tiff", ".tif", ".bmp", ".heic", ".svg"]
        if imageExts.contains(where: { lower.hasSuffix($0) }) { return true }
        if let html, html.range(of: "<img", options: .caseInsensitive) != nil {
            let stripped = html.replacingOccurrences(of: "<[^>]+>", with: "", options: .regularExpression)
                .trimmingCharacters(in: .whitespacesAndNewlines)
            if stripped.count < 80 { return true }
        }
        return false
    }

    private func looksLikeStandaloneURL(_ text: String) -> Bool {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.contains(where: { $0.isNewline }) else { return false }
        if t.hasPrefix("http://") || t.hasPrefix("https://") || t.hasPrefix("file://") || t.hasPrefix("data:image") {
            return URL(string: t) != nil || t.hasPrefix("data:image")
        }
        return false
    }

    private func cappedRichText(_ value: String?) -> String? {
        guard let value, !value.isEmpty, value.utf8.count <= Self.maxRichTextBytes else { return nil }
        return value
    }

    private func cappedRichData(_ value: Data?) -> Data? {
        guard let value, !value.isEmpty, value.count <= Self.maxRichTextBytes else { return nil }
        return value
    }

    private func imagePNGData(from pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: .png) { return png }
        if let tiff = pb.data(forType: .tiff),
           let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]) {
            return png
        }
        return nil
    }

    private func addText(_ text: String, html: String? = nil, rtf: Data? = nil, appName: String? = nil, bundleId: String? = nil) {
        if let first = items.first, first.kind == .text, first.text == text { return }
        insert(ClipItem(kind: .text, text: text, html: html, rtf: rtf, createdAt: Date(), sourceAppName: appName, sourceAppBundleId: bundleId))
    }

    private func addFiles(_ paths: [String], appName: String? = nil, bundleId: String? = nil) {
        guard !paths.isEmpty else { return }
        if let first = items.first, first.kind == .file, first.filePaths == paths { return }
        insert(ClipItem(kind: .file, filePaths: paths, createdAt: Date(), sourceAppName: appName, sourceAppBundleId: bundleId))
    }

    private func addImage(_ pngData: Data, appName: String? = nil, bundleId: String? = nil) {
        let hash = SHA256.hash(data: pngData)
        if let first = items.first, first.kind == .image {
            if lastImageHash == hash {
                return
            }
            if let name = first.imageFile,
               let existing = try? Data(contentsOf: imagesDir.appendingPathComponent(name)),
               SHA256.hash(data: existing) == hash {
                lastImageHash = hash
                return
            }
        }
        let name = "\(UUID().uuidString).png"
        do {
            try pngData.write(to: imagesDir.appendingPathComponent(name))
            lastImageHash = hash
        } catch {
            return
        }
        var size = CGSize.zero
        if let rep = NSBitmapImageRep(data: pngData) {
            size = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
        }
        if let thumb = makeDownsampledImage(from: pngData, maxPixel: Self.thumbnailMaxPixel) {
            imageCache.setObject(thumb, forKey: name as NSString, cost: cacheCost(for: thumb))
        }
        let item = ClipItem(
            kind: .image,
            imageFile: name,
            width: Int(size.width),
            height: Int(size.height),
            createdAt: Date(),
            sourceAppName: appName,
            sourceAppBundleId: bundleId
        )
        insert(item)
        recognizeText(for: item.id, pngData: pngData)
    }

    private func insert(_ item: ClipItem) {
        items.insert(item, at: 0)
        trim()
        save()
        onChanged?()
        if isCollectModeActive {
            pasteQueue.append(item)
            onQueueChanged?()
            NSHapticFeedbackManager.defaultPerformer.perform(.alignment, performanceTime: .default)
        }
    }

    private func trim() {
        let limit = maxItems
        while items.count > limit {
            if let idx = items.lastIndex(where: { !$0.pinned }) {
                removeImageFile(of: items[idx])
                items.remove(at: idx)
                continue
            }
            guard let idx = items.lastIndex(where: { $0.pinned }) else { return }
            removeImageFile(of: items[idx])
            items.remove(at: idx)
        }
    }

    // MARK: - 操作

    func togglePin(_ item: ClipItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[idx].pinned.toggle()
        if items[idx].pinned {
            let pinned = items.remove(at: idx)
            let firstUnpinned = items.firstIndex(where: { !$0.pinned }) ?? items.count
            items.insert(pinned, at: firstUnpinned)
        }
        save()
        onChanged?()
    }

    func remove(_ item: ClipItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        removeImageFile(of: items[idx])
        items.remove(at: idx)
        save()
        onChanged?()
    }

    func clear(preservePinned: Bool = true) {
        if preservePinned {
            let toRemove = items.filter { !$0.pinned }
            for item in toRemove { removeImageFile(of: item) }
            items.removeAll { !$0.pinned }
        } else {
            for item in items { removeImageFile(of: item) }
            items.removeAll()
        }
        imageCache.removeAllObjects()
        previewImageCache.removeAllObjects()
        lastImageHash = nil
        save()
        onChanged?()
    }

    func calculateImageCacheBytes() -> Int64 {
        guard let enumerator = FileManager.default.enumerator(at: imagesDir, includingPropertiesForKeys: [.fileSizeKey], options: [.skipsHiddenFiles]) else {
            return 0
        }
        var total: Int64 = 0
        for case let fileURL as URL in enumerator {
            if let attrs = try? fileURL.resourceValues(forKeys: [.fileSizeKey]),
               let size = attrs.fileSize {
                total += Int64(size)
            }
        }
        return total
    }

    func calculateImageCacheSize() -> String {
        let bytes = calculateImageCacheBytes()
        if bytes > 1024 * 1024 * 1024 {
            return String(format: "%.1f GB", Double(bytes) / (1024.0 * 1024.0 * 1024.0))
        } else if bytes > 1024 * 1024 {
            return String(format: "%.1f MB", Double(bytes) / (1024.0 * 1024.0))
        } else if bytes > 1024 {
            return String(format: "%.1f KB", Double(bytes) / 1024.0)
        } else {
            return "\(bytes) B"
        }
    }

    func cleanExpiredImages(olderThanDays days: Int = 30) {
        let cutoff = Date(timeIntervalSinceNow: -TimeInterval(days * 86400))
        let expiredItems = items.filter { item in
            item.kind == .image && !item.pinned && item.createdAt < cutoff
        }
        for item in expiredItems {
            removeImageFile(of: item)
        }
        items.removeAll { item in
            item.kind == .image && !item.pinned && item.createdAt < cutoff
        }
        let validImageNames = Set(items.compactMap { $0.imageFile })
        if let files = try? FileManager.default.contentsOfDirectory(atPath: imagesDir.path) {
            for file in files {
                if !validImageNames.contains(file) {
                    try? FileManager.default.removeItem(at: imagesDir.appendingPathComponent(file))
                }
            }
        }
        imageCache.removeAllObjects()
        previewImageCache.removeAllObjects()
        save()
        onChanged?()
    }

    func cleanAllUnpinnedImages() {
        let unpinnedImages = items.filter { item in
            item.kind == .image && !item.pinned
        }
        for item in unpinnedImages {
            removeImageFile(of: item)
        }
        items.removeAll { item in
            item.kind == .image && !item.pinned
        }
        let validImageNames = Set(items.compactMap { $0.imageFile })
        if let files = try? FileManager.default.contentsOfDirectory(atPath: imagesDir.path) {
            for file in files {
                if !validImageNames.contains(file) {
                    try? FileManager.default.removeItem(at: imagesDir.appendingPathComponent(file))
                }
            }
        }
        imageCache.removeAllObjects()
        previewImageCache.removeAllObjects()
        save()
        onChanged?()
    }

    /// 把条目写回系统剪贴板（供 Cmd+V 使用），plainTextOnly 为 true 时确保仅写入无格式纯文本
    @discardableResult
    func writeToPasteboard(_ item: ClipItem, plainTextOnly: Bool = false) -> Bool {
        let pb = NSPasteboard.general
        switch item.kind {
        case .text:
            pb.clearContents()
            pb.setString(item.text ?? "", forType: .string)
            if !plainTextOnly {
                if let html = item.html, !html.isEmpty {
                    pb.setString(html, forType: .html)
                }
                if let rtf = item.rtf, !rtf.isEmpty {
                    pb.setData(rtf, forType: .rtf)
                }
            }
        case .image:
            if plainTextOnly {
                guard let ocr = item.ocrText, !ocr.isEmpty else { return false }
                pb.clearContents()
                pb.setString(ocr, forType: .string)
            } else if let name = item.imageFile,
                      let data = try? Data(contentsOf: imagesDir.appendingPathComponent(name)) {
                pb.clearContents()
                pb.setData(data, forType: .png)
            } else {
                return false
            }
        case .file:
            let paths = item.existingFilePaths
            guard !paths.isEmpty else { return false }
            pb.clearContents()
            if plainTextOnly {
                pb.setString(paths.joined(separator: "\n"), forType: .string)
            } else {
                let urls = paths.map { URL(fileURLWithPath: $0) as NSURL }
                pb.writeObjects(urls)
                pb.setString(paths.joined(separator: "\n"), forType: .string)
            }
        }
        lastSeenChangeCount = pb.changeCount
        bumpItemToFront(item)
        return true
    }

    func noteOwnPasteboardWrite() {
        lastSeenChangeCount = NSPasteboard.general.changeCount
    }

    private func bumpItemToFront(_ item: ClipItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        var moved = items.remove(at: idx)
        moved.createdAt = Date()
        if moved.pinned {
            items.insert(moved, at: 0)
        } else {
            let firstUnpinned = items.firstIndex(where: { !$0.pinned }) ?? items.count
            items.insert(moved, at: firstUnpinned)
        }
        save()
        onChanged?()
    }

    func image(for item: ClipItem) -> NSImage? {
        thumbnail(for: item)
    }

    func thumbnail(for item: ClipItem) -> NSImage? {
        guard item.kind == .image, let name = item.imageFile else { return nil }
        if let cached = imageCache.object(forKey: name as NSString) {
            return cached
        }
        let url = imagesDir.appendingPathComponent(name)
        if let img = makeDownsampledImage(from: url, maxPixel: Self.thumbnailMaxPixel) {
            imageCache.setObject(img, forKey: name as NSString, cost: cacheCost(for: img))
            return img
        }
        return nil
    }

    func previewImage(for item: ClipItem) -> NSImage? {
        guard item.kind == .image, let name = item.imageFile else { return nil }
        if let cached = previewImageCache.object(forKey: name as NSString) {
            return cached
        }
        let url = imagesDir.appendingPathComponent(name)
        if let img = makeDownsampledImage(from: url, maxPixel: Self.previewMaxPixel) {
            previewImageCache.setObject(img, forKey: name as NSString, cost: cacheCost(for: img))
            return img
        }
        return nil
    }

    private static let thumbnailMaxPixel = 96
    private static let previewMaxPixel = 1400

    private func makeDownsampledImage(from data: Data, maxPixel: Int) -> NSImage? {
        guard let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary) else {
            return nil
        }
        return makeDownsampledImage(from: source, maxPixel: maxPixel)
    }

    private func makeDownsampledImage(from url: URL, maxPixel: Int) -> NSImage? {
        guard let source = CGImageSourceCreateWithURL(url as CFURL, [kCGImageSourceShouldCache: false] as CFDictionary) else {
            return nil
        }
        return makeDownsampledImage(from: source, maxPixel: maxPixel)
    }

    private func makeDownsampledImage(from source: CGImageSource, maxPixel: Int) -> NSImage? {
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceShouldCacheImmediately: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixel
        ]
        guard let cgImage = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return NSImage(cgImage: cgImage, size: NSSize(width: cgImage.width, height: cgImage.height))
    }

    private func cacheCost(for image: NSImage) -> Int {
        max(Int(image.size.width * image.size.height * 4), 1)
    }

    private func removeImageFile(of item: ClipItem) {
        guard let name = item.imageFile else { return }
        imageCache.removeObject(forKey: name as NSString)
        previewImageCache.removeObject(forKey: name as NSString)
        try? FileManager.default.removeItem(at: imagesDir.appendingPathComponent(name))
    }

    // MARK: - 辅助与扩展

    func setAlias(_ alias: String?, for item: ClipItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        let cleaned = alias?.trimmingCharacters(in: .whitespacesAndNewlines)
        items[idx].alias = (cleaned?.isEmpty == true) ? nil : cleaned
        save()
        onChanged?()
    }

    func imageFileURL(for item: ClipItem) -> URL? {
        guard item.kind == .image, let name = item.imageFile else { return nil }
        let url = imagesDir.appendingPathComponent(name)
        return FileManager.default.fileExists(atPath: url.path) ? url : nil
    }

    func addTextEntry(_ text: String) {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        addText(text)
    }

    // MARK: - Vision 离线文字识别 (OCR)

    private let ocrQueue = DispatchQueue(label: "com.williamlao.clipboardmate.ocr", qos: .utility)

    private func recognizeText(for itemId: UUID, pngData: Data) {
        ocrQueue.async { [weak self] in
            guard let self else { return }
            guard let source = CGImageSourceCreateWithData(pngData as CFData, nil),
                  let cgImage = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return }

            let request = VNRecognizeTextRequest { [weak self] req, error in
                guard let self, error == nil,
                      let observations = req.results as? [VNRecognizedTextObservation] else { return }
                let strings = observations.compactMap { $0.topCandidates(1).first?.string }
                let fullText = strings.joined(separator: "\n").trimmingCharacters(in: .whitespacesAndNewlines)
                guard !fullText.isEmpty else { return }

                DispatchQueue.main.async {
                    if let idx = self.items.firstIndex(where: { $0.id == itemId }) {
                        self.items[idx].ocrText = fullText
                        self.save()
                        self.onChanged?()
                    }
                }
            }

            request.recognitionLevel = .accurate
            request.recognitionLanguages = ["zh-Hans", "zh-Hant", "en-US"]
            request.usesLanguageCorrection = true

            let handler = VNImageRequestHandler(cgImage: cgImage, options: [:])
            try? handler.perform([request])
        }
    }

    // MARK: - 持久化

    private var fileURL: URL { dir.appendingPathComponent("items.json") }
    private var backupURL: URL { dir.appendingPathComponent("items.json.bak") }

    private func load() {
        guard let decoded = decodeHistory(from: fileURL) ?? decodeHistory(from: backupURL) else { return }
        items = decoded.filter { item in
            item.kind != .image || (item.imageFile.map { FileManager.default.fileExists(atPath: imagesDir.appendingPathComponent($0).path) } ?? false)
        }

        let unrecImages = items.filter { $0.kind == .image && $0.ocrText == nil }
        for item in unrecImages.prefix(20) {
            if let name = item.imageFile,
               let data = try? Data(contentsOf: imagesDir.appendingPathComponent(name)) {
                recognizeText(for: item.id, pngData: data)
            }
        }
    }

    private func decodeHistory(from url: URL) -> [ClipItem]? {
        guard let data = try? Data(contentsOf: url), !data.isEmpty else { return nil }
        return try? JSONDecoder().decode([ClipItem].self, from: data)
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        let fm = FileManager.default
        if fm.fileExists(atPath: fileURL.path) {
            try? fm.removeItem(at: backupURL)
            try? fm.copyItem(at: fileURL, to: backupURL)
        }
        try? data.write(to: fileURL, options: .atomic)
    }
}

enum PasteSimulator {
    /// 辅助功能未授权时，一次启动内只引导一次，避免连续按回车反复打断用户。
    private static var hasRequestedPermissionThisLaunch = false

    static var isTrusted: Bool {
        AXIsProcessTrusted()
    }

    /// 用户主动点击授权时调用，弹出系统设置引导
    static func requestPermission() {
        let options = ["AXTrustedCheckOptionPrompt": true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility") {
            NSWorkspace.shared.open(url)
        }
    }

    /// 向当前最前面的应用模拟 Cmd+V，需要辅助功能权限
    @discardableResult
    static func paste() -> Bool {
        guard AXIsProcessTrusted() else {
            if !hasRequestedPermissionThisLaunch {
                hasRequestedPermissionThisLaunch = true
                requestPermission()
            }
            return false
        }
        let source = CGEventSource(stateID: .hidSystemState)
        let vKey = CGKeyCode(9) // kVK_ANSI_V
        let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        down?.flags = .maskCommand
        let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
        return true
    }
}
